# Bumped by hand whenever a BREAKING change is made to the emitted surface (a removed operation,
# a removed/renamed field, a narrowed type). Additive changes do not bump it — they are still
# caught by the golden-artifact test, which is what forces the deliberate regeneration.
WIRE_CONTRACT_VERSION: Final = "0.1.0"

# OpenAPI 3.1 IS JSON-Schema 2020-12 (that is the whole point of 3.1, and the reason we can emit
# ONE definition family and reference it from both artifacts instead of maintaining a translation).
OPENAPI_VERSION: Final = "3.1.0"
SCHEMA_DIALECT: Final = "https://json-schema.org/draft/2020-12/schema"
REF_TEMPLATE: Final = "#/components/schemas/{model}"

ModelRole = Literal["request", "response", "shared"]


class WireParam(BaseModel):
    """One non-body parameter (path or query) of a :class:`WireOperation`."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    name: str = Field(min_length=1)
    location: Literal["path", "query"]
    schema_type: Literal["string", "integer", "number", "boolean"]
    required: bool
    description: str = ""


class WireOperation(BaseModel):
    """One contracted REST operation.

    ``request_model``/``response_model`` name entries of :data:`WIRE_MODELS`. ``request_projected``
    marks the operations whose canonical request model is projected onto path/query params rather
    than sent as a JSON body (``GetRequest``'s own docstring: "``memory_id`` path param,
    ``user``/``session`` as plain query-param function args") — the model is still the contract for
    WHICH fields exist, it just does not appear as a ``requestBody``.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    operation_id: str = Field(min_length=1)
    method: Literal["GET", "POST", "PUT", "DELETE"]
    path: str = Field(pattern=r"^/")
    summary: str = Field(min_length=1)
    request_model: str | None = None
    request_projected: bool = False
    response_model: str = Field(min_length=1)
    success_status: int = Field(ge=200, le=299)
    error_statuses: tuple[int, ...] = ()
    params: tuple[WireParam, ...] = ()


class UncontractedRoute(BaseModel):
    """A route the server serves that the contract does NOT yet cover, plus the concrete reason.

    An entry here is a KNOWN GAP with an owner, not a waiver: the reason names the exact thing that
    has to move for the route to become contractable.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    method: Literal["GET", "POST", "PUT", "DELETE"]
    path: str = Field(pattern=r"^/")
    reason: str = Field(min_length=1)


