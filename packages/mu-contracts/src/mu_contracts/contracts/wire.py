"""The MACHINE-READABLE wire contract — the Phase-0 item this package's ``__init__`` docstring has
been carrying as SCAFFOLD ("the machine-readable OpenAPI + JSON-Schema the TS SDK and community/
conformant servers generate from", ``contracts/__init__.py:11-14``).

**What was missing, and what it cost.** ``PACKAGING-v2.md`` §1.3 puts "the machine-readable
**OpenAPI + JSON-Schema** that the TS SDK and any community/conformant server generate from" in
``contracts/``; ``PACKAGING-v2.md`` §74/§103 and ``mu-local-and-sdk-spec.md`` §C3 both describe
``mu-sdk-js`` as "the TS twin **generated from** ``mu-contracts`` OpenAPI"; and
``api-mcp-surface-spec.md`` §10 / ``api-sdk-mcp-surface-design.md`` §921 require a golden OpenAPI
snapshot that "fails the build if the generated schema drifts". None of that existed: ``git
ls-tree -r HEAD`` found no OpenAPI or JSON-Schema artifact anywhere in the repo, so ``mu-sdk-js``
is in fact HAND-WRITTEN (14 hand-maintained ``.ts`` modules re-declaring the same shapes in zod),
and the "conformant server" story had no machine-readable contract behind it. Two hand-maintained
mirrors of one shape family drift silently; that is the bug this module closes.

**What this module IS.** The single DECLARATIVE statement of the wire surface:

* :data:`WIRE_MODELS` — the named model family that constitutes the wire vocabulary. Every entry
  is an EXISTING pydantic model from this package; nothing here re-declares a shape.
* :data:`WIRE_OPERATIONS` — the REST operations whose request AND response models are both
  canonical ``mu-contracts`` models, with method/path/status/params.
* :data:`UNCONTRACTED_ROUTES` — the routes ``mu-engine-server`` serves that are NOT yet in the
  contract, each with the concrete reason. This list is deliberately EXPLICIT rather than absent:
  ``packages/mu-engine-server/tests/test_wire_contract_routes.py`` asserts the app's real route
  table is exactly ``WIRE_OPERATIONS`` plus ``UNCONTRACTED_ROUTES``, so a new route cannot be added
  without a deliberate decision about whether it is contracted, and a route that becomes
  contractable cannot be quietly left out.
* :func:`build_openapi` / :func:`build_json_schema` — the generator. Pure pydantic
  (``pydantic.json_schema.models_json_schema``); no new dependency, no code generation, no
  hand-written schema text. ``mu-contracts`` stays pydantic-only (``.importlinter``
  ``contracts-imports-nothing-in-project``).

The emitted artifacts are committed under ``mu_contracts/contracts/schema/`` (inside the package,
so they ship in the wheel and any SDK generator can read them from an installed ``mu-contracts``)
and are regenerated by ``mu-core/scripts/wire_contract.py``.

**Why the route inventory is declared here and CHECKED against the app, not read FROM it.**
``mu-contracts`` may not import ``mu_engine_server`` (``.importlinter``:
``contracts-imports-nothing-in-project``), and more importantly the contract is supposed to be the
authority a *third-party* conformant server is measured against — deriving it from our own
``FastAPI`` app would make our implementation definitionally conformant and the contract
meaningless. So the declaration lives here and the app is tested against it.

**Non-goal (named, not hidden): field DEFAULTS are not part of the SDK-parity check.**
``contracts/defaults.py``'s own docstring stages the SDKs' fallback-default wiring as C4, still
open; both SDKs currently carry bare literals (``mu_sdk.models.consolidate.ConsolidateRequest.
limit = 50``, ``mu-sdk-js``'s ``consolidateRequestSchema`` ``.default(50)``) rather than importing
``DEFAULT_CONSOLIDATE_LIMIT``. A parity check that compared defaults would go RED on a
deliberately-staged item and would be disabled within a week. It compares field NAMES,
REQUIRED-ness and JSON type KIND — the three things that make a wire message parse or fail.
"""

