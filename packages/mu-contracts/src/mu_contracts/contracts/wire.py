# --------------------------------------------------------------------------------------
# Generation.
# --------------------------------------------------------------------------------------
# pydantic keys `models_json_schema`'s result by `(type[BaseModel] | type[PydanticDataclass],
# mode)`.
# Every wire model IS a BaseModel, but `PydanticDataclass` is not part of pydantic's public export
# surface (mypy: "does not explicitly export"), so the alias widens the key to `type[Any]` rather
# than importing a private name or silencing the error with a cast.
_SchemaKey = tuple[Any, JsonSchemaMode]


def _definitions() -> tuple[dict[_SchemaKey, str], dict[str, Any]]:
    """Emit ONE shared ``$defs`` family for every wire model, and the key map into it.

    ``models_json_schema`` is the pydantic entry point that resolves shared nested models (e.g.
    ``RecallChannels``, which appears inside both ``RecallRequest`` and ``RecallResult``) to a
    SINGLE definition instead of duplicating it per top-level model. A model is requested in the
    mode its role implies — ``validation`` for a request (what a server must accept),
    ``serialization`` for a response (what a client must be able to read) — and ``shared`` models
    are requested in both, which is exactly how pydantic decides whether one definition suffices
    or the input/output shapes genuinely differ.
    """
    requested: list[tuple[type[BaseModel], JsonSchemaMode]] = []
    for model, role in WIRE_MODELS.values():
        if role in ("request", "shared"):
            requested.append((model, "validation"))
        if role in ("response", "shared"):
            requested.append((model, "serialization"))

    raw_key_map, top = models_json_schema(
        requested,
        ref_template=REF_TEMPLATE,
        title="Memory Universe wire contract",
        schema_generator=GenerateJsonSchema,
    )
    # pydantic hands back ``{(model, mode): {"$ref": "<template-formatted>"}}``; the contract only
    # ever needs the definition KEY, so unwrap once here rather than at every call site.
    key_map = {key: str(ref["$ref"]).rsplit("/", 1)[-1] for key, ref in raw_key_map.items()}
    defs: dict[str, Any] = dict(top.get("$defs", {}))
    return key_map, defs


def _ref_for(key_map: dict[_SchemaKey, str], name: str, mode: JsonSchemaMode) -> str:
    """The ``components/schemas`` key pydantic assigned to ``name`` in ``mode``.

    Fails LOUD (``KeyError``) rather than emitting a dangling ``$ref``: a contract artifact that
    references a schema it does not define is worse than no artifact at all.
    """
    model, _role = WIRE_MODELS[name]
    return key_map[(model, mode)]


def build_json_schema() -> dict[str, Any]:
    """The standalone JSON-Schema artifact: every wire model as a 2020-12 ``$defs`` bundle.

    This is the artifact a non-OpenAPI consumer (a validator, a codegen that speaks JSON-Schema,
    a conformance harness) reads. It carries the SAME definition objects the OpenAPI document's
    ``components.schemas`` carries — one generation, two framings — so the two can never disagree.
    """
    key_map, defs = _definitions()
    roots: dict[str, str] = {}
    for name, (_model, role) in WIRE_MODELS.items():
        if role in ("request", "shared"):
            roots[name if role != "shared" else f"{name}.request"] = _ref_for(
                key_map, name, "validation"
            )
        if role == "response":
            roots[name] = _ref_for(key_map, name, "serialization")
        elif role == "shared":
            roots[f"{name}.response"] = _ref_for(key_map, name, "serialization")

    return {
        "$schema": SCHEMA_DIALECT,
        "$id": (
            "https://schemas.memory-universe.dev/mu-contracts/"
            f"{WIRE_CONTRACT_VERSION}/wire-models.schema.json"
        ),
        "title": "Memory Universe wire models",
        "description": (
            "Machine-readable JSON-Schema for the mu-contracts wire vocabulary "
            "(PACKAGING-v2 §1.3). GENERATED from the pydantic models by "
            "mu-core/scripts/wire_contract.py — do not edit by hand."
        ),
        "x-wire-contract-version": WIRE_CONTRACT_VERSION,
        "x-model-roles": {name: role for name, (_m, role) in WIRE_MODELS.items()},
        "x-schema-key": dict(roots),
        "$defs": defs,
    }


def _operation_object(op: WireOperation, key_map: dict[_SchemaKey, str]) -> dict[str, Any]:
    obj: dict[str, Any] = {
        "operationId": op.operation_id,
        "summary": op.summary,
        "responses": {
            str(op.success_status): {
                "description": "Success.",
                "content": {
                    "application/json": {
                        "schema": {
                            "$ref": REF_TEMPLATE.format(
                                model=_ref_for(key_map, op.response_model, "serialization")
                            )
                        }
                    }
                },
            }
        },
    }
    for status in op.error_statuses:
        obj["responses"][str(status)] = {"description": _ERROR_DESCRIPTIONS[status]}

    if op.params:
        obj["parameters"] = [
            {
                "name": p.name,
                "in": p.location,
                "required": p.required,
                "description": p.description,
                "schema": {"type": p.schema_type},
            }
            for p in op.params
        ]

    if op.request_model is not None and not op.request_projected:
        obj["requestBody"] = {
            "required": True,
            "content": {
                "application/json": {
                    "schema": {
                        "$ref": REF_TEMPLATE.format(
                            model=_ref_for(key_map, op.request_model, "validation")
                        )
                    }
                }
            },
        }
    elif op.request_model is not None:
        # Projected: the canonical model still NAMES the field set, it is just carried as
        # path/query params. Recorded as an extension so a generator can still bind the two.
        obj["x-request-model"] = _ref_for(key_map, op.request_model, "validation")
        obj["x-request-projection"] = "path+query"

    return obj


_ERROR_DESCRIPTIONS: Final[dict[int, str]] = {
    400: "Invalid argument (e.g. an unknown tier).",
    401: "Missing or invalid bearer token.",
    404: "Not found.",
    409: "Refused: the namespace is MANAGED and the caller does not own its lifecycle (ADR 0031).",
    422: "Request body failed schema validation.",
}


def build_openapi() -> dict[str, Any]:
    """The OpenAPI 3.1 artifact for the contracted operations.

    Only :data:`WIRE_OPERATIONS` appear as ``paths``; :data:`UNCONTRACTED_ROUTES` are carried in
    the ``x-uncontracted-routes`` extension WITH their reasons, so a reader of the document sees
    the gap instead of inferring that the surface is five routes wide.
    """
    key_map, defs = _definitions()
    paths: dict[str, dict[str, Any]] = {}
    for op in WIRE_OPERATIONS:
        paths.setdefault(op.path, {})[op.method.lower()] = _operation_object(op, key_map)

    return {
        "openapi": OPENAPI_VERSION,
        "jsonSchemaDialect": SCHEMA_DIALECT,
        "info": {
            "title": "Memory Universe wire contract",
            "version": WIRE_CONTRACT_VERSION,
            "license": {"name": "Apache-2.0"},
            "description": (
                "GENERATED from the mu-contracts pydantic models by "
                "mu-core/scripts/wire_contract.py — do not edit by hand. Covers the operations "
                "whose request AND response models are both canonical mu-contracts models; the "
                "remaining mu-engine-server routes are listed under x-uncontracted-routes with "
                "the reason each is not yet contractable."
            ),
        },
        "components": {
            "schemas": defs,
            "securitySchemes": {
                "bearerAuth": {"type": "http", "scheme": "bearer"},
            },
        },
        "security": [{"bearerAuth": []}],
        "paths": paths,
        "x-uncontracted-routes": [
            {"method": r.method, "path": r.path, "reason": r.reason} for r in UNCONTRACTED_ROUTES
        ],
    }
