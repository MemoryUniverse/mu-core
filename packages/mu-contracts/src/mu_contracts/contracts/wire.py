def wire_model_names(role: ModelRole | None = None) -> tuple[str, ...]:
    """The wire model names, optionally filtered by role (``"shared"`` is never filtered out)."""
    if role is None:
        return tuple(WIRE_MODELS)
    return tuple(name for name, (_model, r) in WIRE_MODELS.items() if r == role or r == "shared")


